
CREATE TABLE work_center (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    title VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE work_center_operation_type (
    work_center_id INTEGER NOT NULL,
    operation_type VARCHAR(20) NOT NULL,

    CONSTRAINT pk_work_center_operation_type
        PRIMARY KEY (work_center_id, operation_type),

    CONSTRAINT fk_work_center_operation_type_work_center
        FOREIGN KEY (work_center_id)
        REFERENCES work_center(id)
        ON DELETE CASCADE
);
