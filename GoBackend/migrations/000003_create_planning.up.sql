-- Планирование производства: расписания станков, планы заказов, плановые операции.
-- См. 01_Go_БД_таблицы_и_поля.docx.

CREATE TABLE work_center_schedule (
    work_center_id INTEGER NOT NULL,
    day_of_week    SMALLINT NOT NULL,
    start_time     TIME WITHOUT TIME ZONE NOT NULL,
    end_time       TIME WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_work_center_schedule
        PRIMARY KEY (work_center_id, day_of_week),

    CONSTRAINT fk_work_center_schedule_work_center
        FOREIGN KEY (work_center_id)
        REFERENCES work_center(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_work_center_schedule_day_of_week
        CHECK (day_of_week BETWEEN 1 AND 7), -- ISO: Пн=1 .. Вс=7

    CONSTRAINT chk_work_center_schedule_time_range
        CHECK (start_time < end_time)
);

CREATE TABLE production_plan (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_order_id INTEGER NOT NULL, -- ProductionOrder.id из Java, без FK
    due_date          DATE NOT NULL, --Желаемая дата готовности включительно; не ограничивает поиск жёстко (см. дока 03, п.13).
    priority          VARCHAR(20) NOT NULL,
    planned_start_at  TIMESTAMPTZ,
    planned_finish_at TIMESTAMPTZ,
    on_time           BOOLEAN,
    status            VARCHAR(20) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_production_plan_priority
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),

    CONSTRAINT chk_production_plan_status
        CHECK (status IN ('PROPOSED', 'ACCEPTED', 'REJECTED', 'CANCELLED')),

    -- Либо план ещё не рассчитан (все три поля NULL), либо рассчитан целиком.
    CONSTRAINT chk_production_plan_times_consistent
        CHECK ( (planned_start_at IS NOT NULL
                 AND planned_finish_at IS NOT NULL
                 AND on_time IS NOT NULL)
             OR (planned_start_at IS NULL
                 AND planned_finish_at IS NULL
                 AND on_time IS NULL) )
);


CREATE INDEX idx_production_plan_external_order_id
    ON production_plan (external_order_id);

CREATE TABLE production_plan_item (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_plan_id     INTEGER NOT NULL,
    external_order_item_id INTEGER NOT NULL, -- ProductionOrderItem.id из Java
    external_product_id    INTEGER NOT NULL, -- Product.id из Java
    quantity               INTEGER NOT NULL,
    planned_start_at       TIMESTAMPTZ,
    planned_finish_at      TIMESTAMPTZ,

    CONSTRAINT fk_production_plan_item_plan
        FOREIGN KEY (production_plan_id)
        REFERENCES production_plan(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_production_plan_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT uq_production_plan_item_order_item
        UNIQUE (production_plan_id, external_order_item_id),
    
    CONSTRAINT chk_production_plan_item_times_consistent
        CHECK ( (planned_start_at IS NOT NULL AND planned_finish_at IS NOT NULL)
             OR (planned_start_at IS NULL AND planned_finish_at IS NULL) ),
            
    CONSTRAINT chk_production_plan_item_time_range
        CHECK (planned_start_at IS NULL OR planned_start_at < planned_finish_at)
);

CREATE INDEX idx_production_plan_item_plan
    ON production_plan_item (production_plan_id);

CREATE TABLE scheduled_operation (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_plan_item_id INTEGER NOT NULL,
    external_operation_id  INTEGER NOT NULL, -- ProductOperation.id из Java
    sequence_number        INTEGER NOT NULL,
    operation_type         VARCHAR(20) NOT NULL,
    work_center_id         INTEGER NOT NULL,
    start_at               TIMESTAMPTZ NOT NULL,
    finish_at              TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_scheduled_operation_plan_item
        FOREIGN KEY (production_plan_item_id)
        REFERENCES production_plan_item(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_scheduled_operation_work_center
        FOREIGN KEY (work_center_id)
        REFERENCES work_center(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_scheduled_operation_sequence_number
        CHECK (sequence_number > 0),

    CONSTRAINT chk_scheduled_operation_time_range
        CHECK (start_at < finish_at)
);

-- Главный индекс занятости: поиск операций станка, пересекающих интервал.
CREATE INDEX idx_scheduled_operation_wc_time
    ON scheduled_operation (work_center_id, start_at, finish_at);

CREATE INDEX idx_scheduled_operation_plan_item
    ON scheduled_operation (production_plan_item_id);